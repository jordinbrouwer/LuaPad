LuaPad = LuaPad or {}
local B = LuaPad.Builder
local Find = B.Find

local UNIT_SWAP_EVENT = { target = "PLAYER_TARGET_CHANGED", focus = "PLAYER_FOCUS_CHANGED" }
local COND_EVENTS = {
  combat = { "PLAYER_REGEN_DISABLED", "PLAYER_REGEN_ENABLED" },
  nocombat = { "PLAYER_REGEN_DISABLED", "PLAYER_REGEN_ENABLED" },
  group = { "GROUP_ROSTER_UPDATE" },
  solo = { "GROUP_ROSTER_UPDATE" },
  instance = { "PLAYER_ENTERING_WORLD" },
}
local COND_CODE = {
  combat = 'UnitAffectingCombat("player")',
  nocombat = 'not UnitAffectingCombat("player")',
  group = "IsInGroup()",
  solo = "not IsInGroup()",
  instance = "(IsInInstance())",
}

local function ActionLines(actions, indent)
  local lines = {}
  for _, a in ipairs(actions) do
    local line
    if a.type == "sound" then
      local id = a.sound == "custom" and tonumber(a.custom) or a.sound
      line = ("Sound(%s)"):format(tostring(id))
    elseif a.type == "text" then
      line = ("Text(%q, %q, %s, %s, %q)"):format(a.text or "", a.color or "white", tostring(a.size or 36), tostring(a.duration or 3), a.pos or "top")
    elseif a.type == "flash" then
      line = ("Flash(%q, %s)"):format(a.color or "red", tostring(a.duration or 1))
    else
      line = ("Print(%q)"):format(a.text or "")
    end
    lines[#lines + 1] = indent .. line
  end
  return lines
end

-- sfx keeps several aura checks apart: "" for the trigger, "C1", "C2", ... for conditions.
local function AuraBlock(spec, sfx)
  local unit = "player"
  for _, u in ipairs(B.UNITS) do
    if u.value == spec.unit then unit = u.value end
  end
  local name = (spec.aura or ""):gsub("^%s+", ""):gsub("%s+$", "")
  local id = tonumber(name)
  local mine = spec.source == "mine"
  local filter = (spec.auraType == "HARMFUL" and "HARMFUL" or "HELPFUL") .. (mine and "|PLAYER" or "")
  local lines = {
    ("local AURA%s = %s"):format(sfx, id and tostring(math.floor(id)) or ("%q"):format(name)),
    ("local FILTER%s = %q"):format(sfx, filter),
    ("local UNIT%s = %q"):format(sfx, unit),
    ("local MIN_STACKS%s = %d"):format(sfx, math.max(1, math.floor(tonumber(spec.stacks) or 1))),
    "",
    "-- The aura's data while it is active (with enough stacks), otherwise nil.",
    ("local function Find%s()"):format(sfx),
    "  local data",
    ('  if type(AURA%s) == "number" then'):format(sfx),
    ("    data = C_UnitAuras and C_UnitAuras.GetUnitAuraBySpellID and C_UnitAuras.GetUnitAuraBySpellID(UNIT%s, AURA%s)"):format(sfx, sfx),
    "  elseif C_UnitAuras and C_UnitAuras.GetAuraDataBySpellName then",
    ("    data = C_UnitAuras.GetAuraDataBySpellName(UNIT%s, AURA%s, FILTER%s)"):format(sfx, sfx, sfx),
    "  end",
    "  if not data then return nil end",
  }
  if mine and id then
    -- Looking up by spell ID can't filter on the caster.
    lines[#lines + 1] = '  if data.sourceUnit ~= "player" and not (issecretvalue and issecretvalue(data.sourceUnit)) then return nil end'
  end
  for _, l in ipairs({
    "  local n = data.applications",
    "  if issecretvalue and issecretvalue(n) then return data end",
    ("  if MIN_STACKS%s > 1 and (n or 0) < MIN_STACKS%s then return nil end"):format(sfx, sfx),
    "  return data",
    "end",
    "",
  }) do lines[#lines + 1] = l end
  return lines, unit
end

local function CdBlock(spell)
  return {
    ("local SPELL = %d"):format(math.floor(tonumber(spell))),
    "",
    "-- Returns known, expires, duration. expires is nil while the spell is ready.",
    "-- known is false when the game hides the cooldown (for example in combat).",
    "local function Cd()",
    "  local info = C_Spell and C_Spell.GetSpellCooldown and C_Spell.GetSpellCooldown(SPELL)",
    "  if not info then return false end",
    "  local start, dur = info.startTime, info.duration",
    "  if issecretvalue and (issecretvalue(start) or issecretvalue(dur)) then return false end",
    "  if start and dur and start > 0 and dur > 1.5 then return true, start + dur, dur end",
    "  return true",
    "end",
    "",
  }
end

function B.Generate(cfg)
  local out = {
    "-- Generated by LuaPad (Simple mode).",
    '-- Press "Convert to code" if you want to take over and edit it by hand.',
    "",
  }
  local function Add(...) for _, l in ipairs({ ... }) do out[#out + 1] = l end end
  local function AddAll(lines) for _, l in ipairs(lines) do out[#out + 1] = l end end
  local problem = B.Validate(cfg)
  if problem then
    Add("-- Not finished yet: " .. problem)
    return table.concat(out, "\n") .. "\n"
  end

  local t = cfg.trigger
  local equipTrigger = t.type == "equip" or t.type == "unequip"
  local isAura = B.AURA_TRIGGERS[t.type]
  local isCd = B.CD_TRIGGERS[t.type]
  local conds = cfg.conds or {}
  local anyCondItem = false
  for _, c in ipairs(conds) do
    if B.ITEM_CONDS[c.type] then anyCondItem = true end
  end
  if B.ITEM_TRIGGERS[t.type] or anyCondItem then
    Add("local IsEquipped = C_Item and C_Item.IsEquippedItem or IsEquippedItem", "")
  end

  local exprs, condUnits = {}, {}
  for i, c in ipairs(conds) do
    if B.AURA_CONDS[c.type] then
      local lines, cunit = AuraBlock(c, "C" .. i)
      AddAll(lines)
      condUnits[#condUnits + 1] = { sfx = "C" .. i, unit = cunit }
      exprs[#exprs + 1] = ("FindC%d() %s"):format(i, c.type == "aura_off" and "== nil" or "~= nil")
    elseif B.ITEM_CONDS[c.type] then
      exprs[#exprs + 1] = (c.type == "item_off" and "not " or "") .. ("IsEquipped(%d)"):format(math.floor(tonumber(c.item)))
    else
      exprs[#exprs + 1] = COND_CODE[c.type]
    end
  end
  local expr
  if #exprs == 1 then
    expr = exprs[1]
  elseif #exprs > 1 then
    for i, e in ipairs(exprs) do exprs[i] = "(" .. e .. ")" end
    expr = table.concat(exprs, cfg.condOp == "or" and " or " or " and ")
  end
  if expr then Add("local function Allowed()", "  return " .. expr, "end", "") end
  local guard = expr and "  if not Allowed() then return end" or nil
  local function Body()
    if guard then Add(guard) end
    for _, l in ipairs(ActionLines(cfg.actions, "  ")) do Add(l) end
  end
  local unit = "player"
  if isAura then
    local lines
    lines, unit = AuraBlock(t, "")
    AddAll(lines)
  elseif isCd then
    AddAll(CdBlock(t.spell))
  end

  local def = Find(B.TRIGGERS, t.type)
  if isAura and t.type ~= "aura_while" then
    -- Switching target or focus is not an aura appearing.
    Add("local was = Find() ~= nil", "",
      'On("UNIT_AURA", function()',
      "  local now = Find() ~= nil",
      "  local before = was",
      "  was = now")
    if t.type == "aura_gain" then
      Add("  if not (now and not before) then return end")
    else
      Add("  if not (before and not now) then return end")
    end
    Body()
    Add("end, UNIT)")
    if UNIT_SWAP_EVENT[unit] then
      Add("", ("On(%q, function() was = Find() ~= nil end)"):format(UNIT_SWAP_EVENT[unit]))
    end
  elseif t.type == "cd_ready" then
    Add("local wasOnCd = false", "",
      "local function Check()",
      "  local known, expires = Cd()",
      "  if not known then return end",
      "  local onCd = expires ~= nil",
      "  local before = wasOnCd",
      "  wasOnCd = onCd",
      "  if not (before and not onCd) then return end")
    Body()
    Add("end", "",
      'On("SPELL_UPDATE_COOLDOWN", function() Check() end)',
      "Every(0.5, function() Check() end)",
      "Check()")
  elseif def and def.event then
    Add(("On(%q, function()"):format(def.event))
    Body()
    Add("end)")
  elseif t.type == "cast" then
    Add('On("UNIT_SPELLCAST_SUCCEEDED", function(event, unit, castGUID, spellID)',
      "  if issecretvalue and issecretvalue(spellID) then return end",
      ("  if spellID ~= %d then return end"):format(math.floor(tonumber(t.spell))))
    Body()
    Add('end, "player")')
  elseif t.type == "resource_reach" or t.type == "resource_gain" then
    local res = Find(B.RESOURCES, t.resource) or B.RESOURCES[1]
    Add(("local POWER = Enum.PowerType.%s"):format(res.enum), "local last = 0", "",
      'On("UNIT_POWER_UPDATE", function(event, unit, powerType)',
      ("  if powerType ~= %q then return end"):format(res.value),
      '  local cur = UnitPower("player", POWER)',
      "  if issecretvalue and issecretvalue(cur) then return end",
      "  local prev = last",
      "  last = cur")
    if t.type == "resource_reach" then
      local n = math.floor(tonumber(t.value))
      Add(("  if not (cur >= %d and prev < %d) then return end"):format(n, n))
    else
      Add("  if not (cur > prev) then return end")
    end
    Body()
    Add('end, "player")')
  elseif t.type == "timer" then
    Add(("Every(%d, function()"):format(math.floor(tonumber(t.seconds))))
    Body()
    Add("end)")
  elseif equipTrigger then
    Add(("local ITEM = %d"):format(math.floor(tonumber(t.item))), "local was = IsEquipped(ITEM)", "",
      'On("PLAYER_EQUIPMENT_CHANGED", function()',
      "  local now = IsEquipped(ITEM)",
      "  local before = was",
      "  was = now")
    if t.type == "equip" then
      Add("  if not (now and not before) then return end")
    else
      Add("  if not (before and not now) then return end")
    end
    Body()
    Add("end)")
  elseif B.STATE_TRIGGERS[t.type] then
    -- Text actions stay on screen while the state holds; other actions fire once when it starts.
    local hasItem = t.type == "item_while"
    local once, texts = {}, {}
    for i, a in ipairs(cfg.actions) do
      if a.type == "text" then texts[#texts + 1] = { i = i, a = a } else once[#once + 1] = a end
    end
    local parts, pre = {}, {}
    if hasItem then parts[#parts + 1] = "IsEquipped(ITEM)" end
    if expr then parts[#parts + 1] = "Allowed()" end
    if hasItem then
      Add(("local ITEM = %d"):format(math.floor(tonumber(t.item))),
        "local ICON = C_Item and C_Item.GetItemIconByID and C_Item.GetItemIconByID(ITEM)")
    elseif isCd then
      Add("local SPELLINFO = C_Spell and C_Spell.GetSpellInfo and C_Spell.GetSpellInfo(SPELL)",
        "local ICON = SPELLINFO and SPELLINFO.iconID")
      pre = { "  local known, expires, dur = Cd()", "  if not known then return end", "  local ready = expires == nil",
        "  local info = expires and { name = SPELLINFO and SPELLINFO.name, expires = expires, duration = dur } or nil" }
      table.insert(parts, 1, t.type == "cd_ready_while" and "ready" or "not ready")
    elseif isAura then
      Add("local ICON = nil", "",
        "local function Plain(v)",
        "  if issecretvalue and issecretvalue(v) then return nil end",
        "  return v",
        "end",
        "-- What %stacks, %time and %name in the text show.",
        "local function InfoOf(data)",
        "  return { name = Plain(data.name), stacks = Plain(data.applications), expires = Plain(data.expirationTime), duration = Plain(data.duration) }",
        "end")
      pre = { "  local data = Find()", "  if data then ICON = data.icon end", "  local info = data and InfoOf(data)" }
      table.insert(parts, 1, "data ~= nil")
    else
      Add("local ICON = nil")
    end
    Add("local shown = false", "", "local function Update(quiet)")
    AddAll(pre)
    Add("  local on = " .. (#parts > 0 and (table.concat(parts, " and ") .. " and true or false") or "true"))
    if #once > 0 then
      Add("  if on and not shown and not quiet then")
      for _, l in ipairs(ActionLines(once, "    ")) do Add(l) end
      Add("  end")
    end
    Add("  shown = on")
    local hasInfo = isAura or isCd
    for _, e in ipairs(texts) do
      local a = e.a
      Add(("  Status(%d, on, %q, %q, %d, %d, %d, %s, %s, %s)"):format(e.i, a.text or "", a.color or "white",
        math.floor(tonumber(a.size) or 36), math.floor(tonumber(a.x) or 0),
        math.floor(tonumber(a.y) or B.TEXT_Y[a.pos or "top"] or 230), a.icon == "text" and "nil" or "ICON",
        hasInfo and "info" or "nil", (hasInfo and a.bar == "bar") and "true" or "false"))
    end
    Add("end", "")
    if hasItem or anyCondItem then Add('On("PLAYER_EQUIPMENT_CHANGED", function() Update() end)') end
    if isAura then
      Add('On("UNIT_AURA", function() Update() end, UNIT)')
      if UNIT_SWAP_EVENT[unit] then Add(("On(%q, function() Update() end)"):format(UNIT_SWAP_EVENT[unit])) end
    end
    if isCd then
      Add('On("SPELL_UPDATE_COOLDOWN", function() Update() end)', "Every(0.5, function() Update() end)")
    end
    local seen, seenUnit = {}, {}
    for _, cu in ipairs(condUnits) do
      if not seenUnit[cu.unit] then
        seenUnit[cu.unit] = true
        Add(("On(\"UNIT_AURA\", function() Update() end, %q)"):format(cu.unit))
        local swap = UNIT_SWAP_EVENT[cu.unit]
        if swap and not seen[swap] then
          seen[swap] = true
          Add(("On(%q, function() Update() end)"):format(swap))
        end
      end
    end
    for _, c in ipairs(conds) do
      for _, ev in ipairs(COND_EVENTS[c.type] or {}) do
        if not seen[ev] then
          seen[ev] = true
          Add(("On(%q, function() Update() end)"):format(ev))
        end
      end
    end
    -- Being logged in with the item already on should stay quiet; "Always" has no such moment.
    Add((hasItem or isAura or isCd) and "Update(true)" or "Update()")
  end
  return table.concat(out, "\n") .. "\n"
end
